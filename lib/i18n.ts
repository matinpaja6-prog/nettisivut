export function translateCategory(locale: Locale, value: string) {
  const normalizedValue = repairTextEncoding(value);
  const directTranslation = categoryTranslations[locale][normalizedValue];
  if (directTranslation) {
    return directTranslation;
  }

  // Category menus often render only the final segment (for example
  // "Kampiakselit") even though the curated dictionary stores the complete
  // path ("Moottorit / Kampiakselit"). Resolve that leaf from the full path
  // instead of leaving it in Finnish or letting automatic DOM translation
  // create a mixed-language label.
  const pathSuffix = ` / ${normalizedValue}`;
  const translatedPath = Object.entries(categoryTranslations[locale])
    .find(([source]) => source.endsWith(pathSuffix))?.[1];

  if (translatedPath) {
    return translatedPath.split(" / ").at(-1)?.trim() || translatedPath;
  }

  if (normalizedValue.includes("/")) {
    return normalizedValue
      .split("/")
      .map((part) => {
        const trimmedPart = part.trim();
        return categoryTranslations[locale][trimmedPart] ?? trimmedPart;
      })
      .join(" / ");
  }

  return normalizedValue;
}

export function useLanguage() {
  const [locale, setLocaleState] = useState<SupportedLocale>("fi");

  useLayoutEffect(() => {
    purgeInvalidLocaleStorage();

    const urlLocale = new URLSearchParams(window.location.search).get("lang");
    if (isLocale(urlLocale)) {
      setLocaleState(urlLocale);
      applyLocale(urlLocale);
      return;
    }

    const storedLocale = localStorage.getItem("locale");
    setLocaleState(normalizeLocale(storedLocale, "fi"));
  }, []);

  function setLocale(nextLocale: SupportedLocale) {
    setLocaleState(nextLocale);
    applyLocale(nextLocale);
  }

  useEffect(() => {
    function handleLocaleChange(event: Event) {
      const nextLocale = (event as CustomEvent<Locale>).detail;
      if (isLocale(nextLocale)) {
        setLocaleState(nextLocale);
      }
    }

    window.addEventListener("localechange", handleLocaleChange);
    return () => window.removeEventListener("localechange", handleLocaleChange);
  }, []);

  return { locale, setLocale, t: translations[locale] };
}

