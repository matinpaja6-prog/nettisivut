export type Locale = SupportedLocale;
export type SupportedLocale = "fi" | "en" | "sv";

const SUPPORTED_LOCALES = ["fi", "en", "sv"] as const;

export function isLocale(value: unknown): value is SupportedLocale {
  return SUPPORTED_LOCALES.includes(value as SupportedLocale);
}

export function normalizeLocale(value: unknown, fallback: SupportedLocale = "fi") {
  return isLocale(value) ? value : fallback;
}

