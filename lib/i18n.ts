export function purgeInvalidLocaleStorage() {
  if (typeof window === "undefined") return;

  try {
    const storedLocale = localStorage.getItem("locale");
    if (!isLocale(storedLocale)) {
      localStorage.removeItem("locale");
    }

    for (let index = localStorage.length - 1; index >= 0; index -= 1) {
      const key = localStorage.key(index);
      if (!key?.startsWith("visitor-language:")) continue;

      const value = localStorage.getItem(key);
      if (!isLocale(value)) {
        localStorage.removeItem(key);
      }
    }

    for (let index = localStorage.length - 1; index >= 0; index -= 1) {
      const key = localStorage.key(index);
      if (!key?.startsWith("auto-ui-translations:")) continue;

      const locale = key.split(":").pop();
      if (!isLocale(locale)) {
        localStorage.removeItem(key);
      }
    }

    const cookieMatch = document.cookie.match(/(?:^|;\s*)locale=([^;]*)/);
    if (!cookieMatch) return;

    const cookieValue = decodeURIComponent(cookieMatch[1] ?? "").trim();
    if (!isLocale(cookieValue)) {
      document.cookie = "locale=; path=/; expires=Thu, 01 Jan 1970 00:00:00 GMT; SameSite=Lax";
    }
  } catch {
    // Ignore local storage/cookie errors from strict browser policies.
  }
}

export function applyLocale(nextLocale: SupportedLocale) {
  if (typeof window === "undefined") return;

  const languageActuallyChanges =
    document.documentElement.lang !== nextLocale ||
    document.documentElement.getAttribute("data-i18n-target") !== nextLocale;

  if (languageActuallyChanges) {
    document.documentElement.setAttribute("data-i18n-target", nextLocale);
    document.documentElement.setAttribute("data-i18n-pending", "true");
    window.setTimeout(() => {
      if (document.documentElement.lang === nextLocale) {
        document.documentElement.removeAttribute("data-i18n-pending");
      }
    }, 1200);
  }
  localStorage.setItem("locale", nextLocale);
  document.cookie = `locale=${nextLocale}; path=/; max-age=31536000; SameSite=Lax`;
  for (let index = 0; index < localStorage.length; index += 1) {
    const key = localStorage.key(index);
    if (key?.startsWith("visitor-language:")) {
      localStorage.setItem(key, nextLocale);
    }
  }
  document.documentElement.lang = nextLocale;
  removeLocaleSearchParam();
  window.dispatchEvent(new CustomEvent("localechange", { detail: nextLocale }));
}

function removeLocaleSearchParam() {
  const url = new URL(window.location.href);
  if (!url.searchParams.has("lang")) return;

  url.searchParams.delete("lang");
  window.history.replaceState(null, "", `${url.pathname}${url.search}${url.hash}`);
}

