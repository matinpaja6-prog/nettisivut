export function glossaryDescription(description: string, locale: string) {
  const index = locale === "en" ? 1 : locale === "sv" ? 2 : locale === "no" ? 3 : 0;
  if (!index) return description;
  // Descriptions also contain structured delivery/vehicle lines. Translate only
  // a complete reviewed line and preserve every other line and separator.
  return description.split(/(\r?\n)/).map(line => {
    const normalized = line.trim().replace(/[.!]+$/, "").toLocaleLowerCase("fi");
    const phrase = descriptionPhrases.find(row => row[0].toLocaleLowerCase("fi") === normalized);
    return phrase ? phrase[index] + (/[.!]$/.test(line.trim()) ? "." : "") : line;
  }).join("");
}

export function validTechnicalTranslation(source: string, translated: string, locale: string, sourceLocale = "fi") {
  if (!translated.trim()) return false;
  const compact = (text: string) => text.toLowerCase().replace(/[^\p{L}\p{N}]/gu, "");
  const target = compact(translated);
  // Substring checks alone would accept 320 as a translation of 32.
  const numbers = (text: string) => text.match(/\d+(?:[.,]\d+)?/g)?.map(value => value.replace(",", ".")) || [];
  const availableNumbers = numbers(translated);
  for (const number of numbers(source)) {
    const at = availableNumbers.indexOf(number);
    if (at < 0) return false;
    availableNumbers.splice(at, 1);
  }
  if (availableNumbers.length > 0) return false;
  // A translation may not drop/change an OEM code, model number or measurement.
  const identifiers = source.match(/[\p{L}\p{N}.-]*\d[\p{L}\p{N}.-]*/gu) || [];
  if (identifiers.some(id => !target.includes(compact(id)))) return false;
  for (const patterns of limitationPatterns) {
    const sourcePattern = patterns[sourceLocale as keyof typeof patterns];
    const targetPattern = patterns[locale as keyof typeof patterns];
    if (sourcePattern?.test(source) && !sourcePattern.test(translated) && !targetPattern?.test(translated)) return false;
  }
  if (sourceLocale !== "fi" || locale === "fi") return true;
  const index = locale === "en" ? 1 : locale === "sv" ? 2 : 3;
  // Reject the known carburetor -> water bottle class of error.
  const carburetor = partGlossary[0];
  if (termPattern(carburetor[0]).test(source) &&
      !target.includes(compact(carburetor[index])) &&
      !termPattern(carburetor[0]).test(translated)) return false;
  return true;
}
