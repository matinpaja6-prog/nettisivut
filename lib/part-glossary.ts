function termPattern(variants: string) {
  return new RegExp("(?<![\\p{L}])(?:" + variants + ")(?![\\p{L}])", "giu");
}

const titleTerms = [...partGlossary]
  .sort((a, b) => b[0].length - a[0].length)
  .map(entry => ({ entry, pattern: termPattern(entry[0]) }));

export function glossaryTitle(title: string, locale: string) {
  const index = locale === "en" ? 1 : locale === "sv" ? 2 : locale === "no" ? 3 : 0;
  if (!index) return title;
  // Long phrases first; placeholders prevent translating the output a second time.
  const replacements: string[] = [];
  let result = title;
  for (const { entry, pattern } of titleTerms) {
    result = result.replace(pattern, () => {
      replacements.push(entry[index]);
      return "\u0001" + (replacements.length - 1) + "\u0002";
    });
  }
  result = result.replace(/\u0001(\d+)\u0002/g, (_, index) => replacements[Number(index)]);
  // Two synonymous category labels can translate into the exact same phrase.
  // Collapse only adjacent, slash-separated curated terms; never OEMs or free text.
  for (const entry of partGlossary) {
    const term = entry[index].replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    result = result.replace(new RegExp(`(?<![\\p{L}])(${term})(?:\\s*/\\s*${term})+(?![\\p{L}])`, "giu"), "$1");
  }
  return result;
}

